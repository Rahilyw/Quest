#!/usr/bin/env bash
# Generate packages/db-types/src/database.ts from the M1 throwaway stack.
# Prerequisites: apply.sh left the stack running (or DB_URL points at it).
# With --check (default in CI): fail if the committed file drifts.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
WORK="$ROOT/scripts/db-local/.stack"
OUT="$ROOT/packages/db-types/src/database.ts"
CHECK=1

for arg in "$@"; do
  case "$arg" in
    --no-check) CHECK=0 ;;
    --check) CHECK=1 ;;
  esac
done

if [[ ! -d "$WORK/supabase" ]]; then
  echo "types: missing $WORK — run scripts/db-local/apply.sh first" >&2
  exit 1
fi

mkdir -p "$(dirname "$OUT")"
TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT

echo "types: generating from local stack (workdir $WORK)…"
(
  cd "$WORK"
  # Prefer --local against the running stack; fall back to DB_URL.
  if supabase gen types typescript --local --schema public >"$TMP" 2>/tmp/gen-types.err; then
    :
  else
    echo "types: --local failed; trying DB_URL…" >&2
    cat /tmp/gen-types.err >&2 || true
    if [[ -z "${DB_URL:-}" && -f "$ROOT/scripts/db-local/.db-url" ]]; then
      DB_URL="$(tr -d '[:space:]' < "$ROOT/scripts/db-local/.db-url")"
    fi
    if [[ -z "${DB_URL:-}" ]]; then
      echo "types: no DB_URL for fallback" >&2
      exit 1
    fi
    supabase gen types typescript --db-url "$DB_URL" --schema public >"$TMP"
  fi
)

# Header so the committed file is clearly generated.
{
  echo '// Generated by scripts/db-local/types.sh — do not edit by hand.'
  echo '// Regenerate against the M1 stack: scripts/db-local/apply.sh && scripts/db-local/types.sh'
  echo
  cat "$TMP"
} >"$OUT"

echo "types: wrote $OUT ($(wc -l < "$OUT") lines)"

if [[ "$CHECK" -eq 1 ]]; then
  echo "types: drift check (git diff --exit-code packages/db-types)…"
  git -C "$ROOT" diff --exit-code -- packages/db-types
  echo "types: committed types match generated output"
fi
